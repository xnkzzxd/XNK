'use strict';
// Builds app/share.html (the share-card editor for the standalone app) from the panel's own files:
// Theme.html (styles) + Bagikan.html (renderer). Never edit app/share.html by hand; edit the sources
// or app/share-shim.js (the few globals Bagikan expects from App.html), then run:
//   node apps-script/pt-scheduler/tools/build-app-share.js          (write)
//   node apps-script/pt-scheduler/tools/build-app-share.js --check  (fail when out of date)
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(__dirname, '..', '..', '..', 'app', 'share.html');

function build() {
  const theme = fs.readFileSync(path.join(SRC, 'Theme.html'), 'utf8');
  const bag = fs.readFileSync(path.join(SRC, 'Bagikan.html'), 'utf8');
  const css = /<style>([\s\S]*?)<\/style>/.exec(theme)[1];
  const js = /<script>([\s\S]*)<\/script>/.exec(bag)[1];
  return `<!doctype html>
<!-- GENERATED by apps-script/pt-scheduler/tools/build-app-share.js from Theme.html + Bagikan.html. Do not edit. -->
<html lang="id"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, minimum-scale=1, viewport-fit=cover">
<title>Bagikan</title>
<style>${css}</style>
<style>html,body{height:100%;margin:0}.layer{position:fixed;inset:0}#share-toast{position:fixed;left:16px;right:16px;bottom:24px;background:#111;color:#fff;padding:12px;border-radius:10px;display:none;z-index:99;text-align:center}</style>
</head><body>
<div class="layer open" id="sheet-layer"><div class="sheet tall hide" id="sheet-share"></div></div>
<div id="share-toast"></div>
<script src="share-shim.js"></script>
<script>${js}</script>
<script>window.parent.postMessage({ xk: 'ready' }, '*');</script>
</body></html>
`;
}

module.exports = { build, OUT };
if (require.main === module) {
  const html = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== html) { console.error('app/share.html is out of date. Run tools/build-app-share.js'); process.exit(1); }
    console.log('app/share.html up to date');
  } else { fs.writeFileSync(OUT, html); console.log('wrote', OUT, html.length, 'bytes'); }
}
