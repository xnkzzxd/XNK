'use strict';
// Builds src/Api.gs: the table of server functions that doPost may dispatch (Phase AAA).
// Source of truth is tests/api-lists.js (the same lists security.test.js classifies from).
// Never edit src/Api.gs by hand. After adding a server function to a list there, run:
//   node apps-script/pt-scheduler/tools/build-api.js          (write)
//   node apps-script/pt-scheduler/tools/build-api.js --check  (fail when out of date)
const fs = require('fs');
const path = require('path');
const L = require('../tests/api-lists');
const OUT = path.join(__dirname, '..', 'src', 'Api.gs');

function group(title, names) {
  return `    // ${title} (${names.length})\n` + names.map(n => `    ${n}: ${n},`).join('\n');
}

function build() {
  return `// GENERATED by apps-script/pt-scheduler/tools/build-api.js from tests/api-lists.js. Do not edit.
// Every function doPost may call. Each one still guards itself (requireAdmin_ / requireMember_
// as its first statement), so this table is a door list, not a permission list. Owner-only
// (requireOwner_) functions, trigger handlers, doGet/doPost/include and helpers are not in it.
function _apiTable_() {
  return {
${group('public: no token', L.PUBLIC_API)}
${group('admin: admin token', L.ADMIN)}
${group('member: member token', L.MEMBER)}
  };
}
`;
}

module.exports = { build, OUT };

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('src/Api.gs is out of date: run node apps-script/pt-scheduler/tools/build-api.js'); process.exit(1); }
    console.log('Api.gs up to date');
  } else {
    fs.writeFileSync(OUT, out);
    console.log('wrote ' + path.relative(process.cwd(), OUT) + ' (' + L.API_FUNCTIONS.length + ' functions)');
  }
}
